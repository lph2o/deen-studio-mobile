/// Get a template by its ID.
Template getTemplateById(String id) {
  return kBuiltInTemplates.firstWhere(
    (t) => t.id == id,
    orElse: () => kBuiltInTemplates.first,
  );
}

/// Get templates filtered by category.
List<Template> getTemplatesByCategory(String category) {
  if (category == 'All') return kBuiltInTemplates;
  return kBuiltInTemplates.where((t) => t.category == category.toLowerCase()).toList();
}
